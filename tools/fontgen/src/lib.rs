//! GNU Unifont `.hex` glyphs (8x16 or 16x16 bitmaps) to a compact C table for the PSP.

use std::collections::BTreeMap;
use std::fmt::Write;

pub type Glyphs = BTreeMap<u32, Vec<u8>>;

/// Code points the PSP renders: ASCII, Latin-1, Latin Extended-A, the Vietnamese horn letters,
/// Latin Extended Additional (Vietnamese tone marks), punctuation, currency, arrows, shapes, U+FFFD.
pub const RANGES: &[(u32, u32)] = &[
    (0x20, 0x7E),
    (0xA0, 0xFF),
    (0x100, 0x17F),
    (0x1A0, 0x1A1),
    (0x1AF, 0x1B0),
    (0x1EA0, 0x1EF9),
    (0x2010, 0x2027),
    (0x20AB, 0x20AC),
    (0x2190, 0x2193),
    (0x25A0, 0x25CF),
    (0xFFFD, 0xFFFD),
];

pub fn parse_hex(text: &str) -> Result<Glyphs, String> {
    let mut out = Glyphs::new();
    for (n, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (cp, bits) = line.split_once(':').ok_or_else(|| format!("line {}: missing ':'", n + 1))?;
        let cp = u32::from_str_radix(cp, 16).map_err(|e| format!("line {}: {e}", n + 1))?;
        if bits.len() != 32 && bits.len() != 64 {
            return Err(format!("line {}: glyph must be 8x16 or 16x16", n + 1));
        }
        let bytes = (0..bits.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&bits[i..i + 2], 16))
            .collect::<Result<Vec<u8>, _>>()
            .map_err(|e| format!("line {}: {e}", n + 1))?;
        out.insert(cp, bytes);
    }
    Ok(out)
}

pub fn subset(all: &Glyphs) -> String {
    let mut s = String::from(
        "# Subset of GNU Unifont 18.0.01 (SIL Open Font License 1.1, see OFL-1.1.txt).\n\
         # Regenerate psp/font_vi.c with: cargo run -p pspc-fontgen\n",
    );
    for (cp, bits) in all {
        if RANGES.iter().any(|(a, b)| (a..=b).contains(&cp)) {
            let hex: String = bits.iter().map(|b| format!("{b:02X}")).collect();
            let _ = writeln!(s, "{cp:04X}:{hex}");
        }
    }
    s
}

fn join_rows<T: std::fmt::Display>(items: impl Iterator<Item = T>, per_row: usize) -> String {
    let items: Vec<String> = items.map(|i| i.to_string()).collect();
    items.chunks(per_row).map(|c| format!("    {},", c.join(", "))).collect::<Vec<_>>().join("\n")
}

pub fn generate_c(glyphs: &Glyphs) -> String {
    let mut offsets = Vec::with_capacity(glyphs.len());
    let mut offset = 0usize;
    for data in glyphs.values() {
        offsets.push(offset);
        offset += data.len();
    }
    format!(
        "/* Generated by tools/fontgen from psp/assets/font-vi.hex (GNU Unifont subset, SIL OFL 1.1). Do not edit. */\n\
         #include \"font.h\"\n\n\
         const unsigned font_vi_count = {count};\n\n\
         const uint16_t font_vi_codes[] = {{\n{codes}\n}};\n\n\
         const uint16_t font_vi_offsets[] = {{\n{offsets}\n}};\n\n\
         const uint8_t font_vi_widths[] = {{\n{widths}\n}};\n\n\
         const uint8_t font_vi_bits[] = {{\n{bits}\n}};\n",
        count = glyphs.len(),
        codes = join_rows(glyphs.keys().map(|cp| format!("0x{cp:04X}")), 12),
        offsets = join_rows(offsets.iter(), 12),
        widths = join_rows(glyphs.values().map(|d| d.len() / 2), 24),
        bits = join_rows(glyphs.values().flatten().map(|b| format!("0x{b:02X}")), 16),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn committed(name: &str) -> String {
        std::fs::read_to_string(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../psp").join(name)).unwrap()
    }

    #[test]
    fn committed_font_matches_its_source() {
        let glyphs = parse_hex(&committed("assets/font-vi.hex")).unwrap();
        assert!(generate_c(&glyphs) == committed("font_vi.c"), "stale font_vi.c: run cargo run -p pspc-fontgen");
    }

    #[test]
    fn covers_every_vietnamese_letter() {
        let glyphs = parse_hex(&committed("assets/font-vi.hex")).unwrap();
        let vi = "aàáảãạăằắẳẵặâầấẩẫậbcdđeèéẻẽẹêềếểễệghiìíỉĩịklmnoòóỏõọôồốổỗộơờớởỡợpqrstuùúủũụưừứửữựvxyỳýỷỹỵ";
        for c in vi.chars().chain(vi.to_uppercase().chars()).chain("0123456789.,!?…–“”₫".chars()) {
            assert!(glyphs.contains_key(&(c as u32)), "missing {c} U+{:04X}", c as u32);
        }
        assert!(glyphs.keys().all(|cp| *cp <= 0xFFFF), "code points fit in uint16_t");
    }

    #[test]
    fn rejects_bad_lines() {
        assert!(parse_hex("41:00").is_err());
        assert!(parse_hex("zz:00000000000000000000000000000000").is_err());
        assert_eq!(parse_hex("# c\n0041:0000000018242442427E424242420000\n").unwrap().len(), 1);
    }
}
